/**
 * 能力选用协议。
 *
 * 为什么单独一段、且排在装配层的所有正文之后：
 *   宿主把所有「名字命中特定前缀」的段按插入序挪到最前（renderPrompt 里有一步
 *   startsWith 过滤）。如果这一段和正文用同一个前缀，它会被拉到正文之前，
 *   造成「能力说明在前、做法在后」的渲染反转，模型会先读方法论再读任务，
 *   实测这种顺序下更容易把方法论当成限制条件来解读。
 *   所以段名带独立前缀，order 显式排在正文之后。
 *
 * 三条纪律写在协议里，而不是写成规则：
 *   - 先看目录再动手（避免重复造轮子，也避免拿错工具）；
 *   - 匹配才调，不匹配就自己写，并说清楚缺什么；
 *   - 子代理继承这条，派活时写进 brief。
 */

export const CAPABILITY_SECTION = 'armor:capabilities'
/** 正文最后一段是 armor:ban(10430)，能力协议排它之后、锚点(10500)之前。 */
export const CAPABILITY_ORDER = 10450

export const MAIN_PROTOCOL = `[能力选用]

1. 动手之前先看手上有什么：可用技能清单、可用的 MCP 工具、可用的命令行。这一步不是形式，看漏了就会用错工具或多写一遍已经有现成实现的东西。
2. 按任务匹配，不是全部调用，也不是一律不用。匹配的判据是「这个东西的方法、前提、失败分支，能不能直接省掉我一段推导」。
3. 匹配上了就真调：技能按其方法、前提、分支、反证执行；工具用它的真实参数名与上下文调用，失败按它的语义处理，不自己编返回值。
4. 一个都不匹配，就自己写，并说明缺哪一块。不要为了「显得用了工具」去调不相关的工具。
5. 派活给子代理时，把第 1–4 条写进它的任务说明里。子代理不会自动继承这段。
6. 不删除、不覆盖宿主提供的能力入口。`

export const LEAD_PROTOCOL = `[调度层能力选用]

1. 调度层只做四件事：定方案、派活、验结果、汇总。具体工件由执行层产出。
2. 派活之前先知道下一阶段该用哪个技能或哪个工具。不知道就先查目录，不要凭印象派。
3. 每份子任务说明里都要写：先读可用目录，再只调所需的那几个。不写这条，子代理会自己造轮子。
4. 叶子限制只约束「继续往下委派」这一类工具（再派子代理、再开工作流）。技能与工具调用不受此限，子代理该调就调。
5. 「去看看这个」不是任务。「用 X 方法确认 Y 字段，把 Z 的对齐方式报回来，附命令与输出」才是。`

export function capabilityText({ isChild = false, isLead = false, enabled = true } = {}) {
  if (!enabled) return ''
  if (isChild) return ''
  return isLead ? `${MAIN_PROTOCOL}\n\n${LEAD_PROTOCOL}` : MAIN_PROTOCOL
}
