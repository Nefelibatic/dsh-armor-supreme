/**
 * 生成某家族的表面层正文。
 * @param {string} providerKey
 * @param {{ zeroPreamble?: boolean }} [opts]
 */
export function surfaceText(providerKey = 'generic', opts = {}) {
  const p = profileOf(providerKey)
  const body = BY_PROVIDER[p.key] || BY_PROVIDER.generic
  const preamble = p.zeroPreamble === false
    ? ''
    : `\n\n## 零前言\n\n第一段之前不出现任何过渡。不要复述问题，不要声明将要做什么，不要请求确认。`
  return [COMMON_HEAD, '', OPENING, '', body, preamble, '', SHARED_BANS, '', SHARED_TAIL].join('\n')
}

